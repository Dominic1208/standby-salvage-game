def build() -> list[dict]:
    items = []
    for si, (series, art, tint, objects) in enumerate(SERIES):
        # 每个系列 5 个版本：1 个常见、1 个少见、1 个稀有、1 个史诗、1 个传说，从各档里错开挑
        by_rarity = {r: [e for e in EDITIONS if e[1] == r] for r in range(1, 6)}
        editions = [by_rarity[r][si % len(by_rarity[r])] for r in range(1, 6)]
        for oi, (obj, odesc) in enumerate(objects):
            for ei, (ename, rarity, edesc) in enumerate(editions):
                items.append({
                    "id": f"s{si:02d}_{oi}{ei}",
                    "name": f"{obj}·{ename}",
                    "rarity": rarity,
                    "desc": f"{odesc}{edesc}",
                    "series": series,
                    "art": f"col_series_{si:02d}" if (ART_DIR / f"col_series_{si:02d}.png").exists() else art,
                    "tint": tint,
                })
    return items


def main() -> None:
    data = json.loads(GIFTS.read_text("utf-8"))
    handmade = [c for c in data["collectibles"] if "series" not in c or c["series"] == "开店纪念"]
    for c in handmade:
        c["series"] = "开店纪念"
        c["art"] = "col_" + c["id"]
    data["collectibles"] = handmade + build()
    GIFTS.write_text(json.dumps(data, ensure_ascii=False, indent=1), "utf-8")
    names = [c["name"] for c in data["collectibles"]]
    assert len(names) == len(set(names)), "有重名"
    print(f"收藏品共 {len(data['collectibles'])} 件，系列 {len(SERIES) + 1} 个")


if __name__ == "__main__":
    main()
